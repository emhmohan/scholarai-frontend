import { useState } from 'react';
import toast from 'react-hot-toast';
import api from '../utils/api';
import { Mic, Sparkles, ChevronDown, ChevronUp, CheckCircle, XCircle, Send, Download } from 'lucide-react';
import jsPDF from 'jspdf';

const CAT_COLORS = {
  'Motivation':          'var(--y)',
  'Academic background': 'var(--b-1)',
  'Career goals':        'var(--y)',
  'Leadership':          '#34d399',
  'Research':            'var(--b-1)',
  'Challenges':          '#f87171',
  'Community':           '#34d399',
  'default':             'var(--muted)',
};

export default function InterviewPage() {
  const [scholarshipName, setScholarshipName] = useState('');
  const [loading,         setLoading]         = useState(false);
  const [data,            setData]            = useState(null);
  const [expanded,        setExpanded]        = useState(null);
  const [practicing,      setPracticing]      = useState(null);
  const [answer,          setAnswer]          = useState('');
  const [feedback,        setFeedback]        = useState({});
  const [feedbackLoading, setFeedbackLoading] = useState(false);

  const handlePrepare = async () => {
    if (!scholarshipName.trim()) { toast.error('Enter a scholarship name'); return; }
    setLoading(true);
    setData(null);
    setFeedback({});
    try {
      const res = await api.post('/interview/prepare', { scholarshipName });
      setData(res.data.data);
      toast.success('Interview prep ready!');
    } catch (err) {
      toast.error(err.response?.data?.message || 'Failed to generate prep');
    } finally { setLoading(false); }
  };

  const handleGetFeedback = async (question, idx) => {
    if (!answer.trim()) { toast.error('Write your answer first'); return; }
    setFeedbackLoading(true);
    try {
      const res = await api.post('/interview/feedback', { question, answer });
      setFeedback((p) => ({ ...p, [idx]: res.data.data }));
      toast.success('Feedback ready!');
    } catch { toast.error('Failed to get feedback'); }
    finally  { setFeedbackLoading(false); }
  };

  const handleDownloadPDF = () => {
    if (!data) return;
    const doc = new jsPDF();
    const w   = doc.internal.pageSize.getWidth();
    const h   = doc.internal.pageSize.getHeight();
    const m   = 20;

    // Cover
    doc.setFillColor(5,5,7); doc.rect(0,0,w,h,'F');
    doc.setFillColor(245,197,24); doc.rect(0,0,w,4,'F');
    doc.setTextColor(255,255,255);
    doc.setFontSize(28); doc.setFont('helvetica','bold');
    doc.text('Interview Preparation', w/2, 80, { align:'center' });
    doc.setFontSize(16); doc.setFont('helvetica','normal');
    doc.text('Guide', w/2, 95, { align:'center' });
    doc.setFontSize(18); doc.setFont('helvetica','bold');
    doc.setTextColor(245,197,24);
    doc.text(scholarshipName, w/2, 130, { align:'center' });
    doc.setFontSize(11); doc.setFont('helvetica','normal'); doc.setTextColor(100,100,100);
    doc.text(`${data.commonQuestions?.length || 0} Questions · Generated by ScholarAI · ${new Date().toLocaleDateString()}`, w/2, h-20, { align:'center' });

    // Page 2: Overview
    doc.addPage();
    let y = 20;
    doc.setFillColor(245,197,24); doc.rect(0,0,w,3,'F');
    doc.setTextColor(245,197,24); doc.setFontSize(14); doc.setFont('helvetica','bold');
    doc.text('OVERVIEW', m, y+10); y += 18;
    doc.setTextColor(50,50,50); doc.setFontSize(10); doc.setFont('helvetica','normal');
    const overviewLines = doc.splitTextToSize(data.overview||'', w-m*2);
    overviewLines.forEach((l) => { doc.text(l,m,y); y+=6; });
    y += 6;

    if (data.dosList?.length > 0) {
      doc.setTextColor(34,197,94); doc.setFontSize(12); doc.setFont('helvetica','bold');
      doc.text("DO'S", m, y); y += 8;
      data.dosList.forEach((d) => {
        doc.setTextColor(50,50,50); doc.setFontSize(10); doc.setFont('helvetica','normal');
        doc.text(`• ${d}`, m+4, y); y += 6;
      }); y += 4;
    }

    if (data.dontsList?.length > 0) {
      doc.setTextColor(239,68,68); doc.setFontSize(12); doc.setFont('helvetica','bold');
      doc.text("DON'TS", m, y); y += 8;
      data.dontsList.forEach((d) => {
        doc.setTextColor(50,50,50); doc.setFontSize(10); doc.setFont('helvetica','normal');
        doc.text(`• ${d}`, m+4, y); y += 6;
      });
    }

    // Questions
    data.commonQuestions?.forEach((q, idx) => {
      doc.addPage();
      doc.setFillColor(245,197,24); doc.rect(0,0,w,3,'F');
      y = 18;
      doc.setTextColor(150,150,150); doc.setFontSize(9); doc.setFont('helvetica','normal');
      doc.text(`Question ${idx+1} of ${data.commonQuestions.length} · ${q.category}`, m, y); y += 10;
      doc.setFillColor(248,248,255);
      const qLines = doc.splitTextToSize(q.question, w-m*2-8);
      doc.roundedRect(m, y, w-m*2, qLines.length*7+10, 3, 3, 'F');
      doc.setTextColor(20,20,20); doc.setFontSize(12); doc.setFont('helvetica','bold');
      qLines.forEach((l,i) => { doc.text(l, m+5, y+8+i*7); });
      y += qLines.length*7+16;
      if (q.tips) {
        doc.setTextColor(34,197,94); doc.setFontSize(10); doc.setFont('helvetica','bold');
        doc.text('Tips:', m, y); y += 6;
        doc.setTextColor(60,60,60); doc.setFont('helvetica','normal');
        const tipLines = doc.splitTextToSize(q.tips, w-m*2-4);
        tipLines.forEach((l) => { doc.text(l,m+4,y); y+=5; }); y+=6;
      }
      doc.setTextColor(150,150,150); doc.setFontSize(10); doc.setFont('helvetica','bold');
      doc.text('Practice Space:', m, y); y += 6;
      doc.setDrawColor(200,200,200); doc.setLineWidth(0.3);
      for (let i=0;i<6;i++) { doc.line(m,y,w-m,y); y+=9; }
    });

    doc.save(`Interview_${scholarshipName.replace(/\s+/g,'_')}.pdf`);
    toast.success('Guide downloaded!');
  };

  const scoreColor = (s) => s >= 8 ? '#34d399' : s >= 6 ? 'var(--y)' : '#f87171';

  return (
    <div style={{ maxWidth: 900, margin: '0 auto' }}>

      {/* Header */}
      <div className="afu" style={{ display: 'flex', alignItems: 'center', justifyContent: 'space-between', flexWrap: 'wrap', gap: 16, marginBottom: 24 }}>
        <div style={{ display: 'flex', alignItems: 'center', gap: 12 }}>
          <div style={{ width: 38, height: 38, borderRadius: 11, background: 'var(--y-dim)', border: '1px solid var(--y-border)', display: 'flex', alignItems: 'center', justifyContent: 'center' }}>
            <Mic size={19} style={{ color: 'var(--y)' }} />
          </div>
          <div>
            <h1 style={{ fontFamily: 'Space Grotesk', fontSize: 22, fontWeight: 800, color: 'var(--white)' }}>Interview Preparation</h1>
            <p style={{ fontSize: 13, color: 'var(--muted)' }}>AI questions + practice + downloadable guide</p>
          </div>
        </div>
        {data && (
          <button onClick={handleDownloadPDF}
            className="btn-p"
            style={{ display: 'flex', alignItems: 'center', gap: 8, padding: '10px 20px', borderRadius: 11, background: 'var(--g-y)', color: '#000', fontSize: 13, fontWeight: 700, border: 'none', cursor: 'pointer' }}>
            <Download size={14} /> Download Guide
          </button>
        )}
      </div>

      {/* Input */}
      <div className="afu" style={{ borderRadius: 16, padding: '22px', background: 'var(--bg-2)', border: '1px solid var(--border)', marginBottom: 20 }}>
        <label style={{ display: 'block', fontSize: 11, fontWeight: 700, color: 'var(--muted)', marginBottom: 8, textTransform: 'uppercase', letterSpacing: '0.04em' }}>
          Scholarship / Program Name
        </label>
        <div style={{ display: 'flex', gap: 10 }}>
          <input value={scholarshipName} onChange={(e) => setScholarshipName(e.target.value)}
            onKeyDown={(e) => e.key === 'Enter' && handlePrepare()}
            placeholder="e.g. Fulbright, Gates Cambridge, PMRF..."
            style={{ flex: 1, padding: '11px 14px', borderRadius: 10, background: 'var(--bg-3)', border: '1px solid var(--border)', color: 'var(--white-1)', fontSize: 13, outline: 'none' }}
            onFocus={(e) => { e.target.style.borderColor = 'var(--y)'; e.target.style.boxShadow = '0 0 0 3px rgba(245,197,24,0.08)'; }}
            onBlur={(e)  => { e.target.style.borderColor = 'var(--border)'; e.target.style.boxShadow = 'none'; }} />
          <button onClick={handlePrepare} disabled={loading}
            className="btn-p"
            style={{ display: 'flex', alignItems: 'center', gap: 8, padding: '11px 22px', borderRadius: 10, background: loading ? 'var(--bg-4)' : 'var(--g-y)', color: loading ? 'var(--muted)' : '#000', fontSize: 13, fontWeight: 700, border: 'none', cursor: loading ? 'not-allowed' : 'pointer', flexShrink: 0 }}>
            <Sparkles size={14} />
            {loading ? 'Preparing...' : 'Prepare'}
          </button>
        </div>

        {/* Quick select */}
        <div style={{ display: 'flex', flexWrap: 'wrap', gap: 6, marginTop: 12 }}>
          <span style={{ fontSize: 11, color: 'var(--muted)', alignSelf: 'center' }}>Quick:</span>
          {['Fulbright','Chevening','Gates Cambridge','DAAD','PMRF','Rhodes','Commonwealth','Inlaks'].map((s) => (
            <button key={s} onClick={() => setScholarshipName(s)}
              style={{ padding: '5px 12px', borderRadius: 99, fontSize: 11, fontWeight: 600, background: 'var(--bg-3)', border: '1px solid var(--border)', color: 'var(--muted)', cursor: 'pointer', transition: 'all 0.2s' }}
              onMouseEnter={(e) => { e.currentTarget.style.borderColor = 'var(--y-border)'; e.currentTarget.style.color = 'var(--y)'; }}
              onMouseLeave={(e) => { e.currentTarget.style.borderColor = 'var(--border)'; e.currentTarget.style.color = 'var(--muted)'; }}>
              {s}
            </button>
          ))}
        </div>
      </div>

      {/* Loading */}
      {loading && (
        <div className="afu" style={{ borderRadius: 16, padding: '32px', textAlign: 'center', background: 'var(--bg-2)', border: '1px solid var(--y-border)', marginBottom: 20 }}>
          <div style={{ width: 36, height: 36, borderRadius: '50%', border: '2px solid var(--y)', borderTopColor: 'transparent', animation: 'spinSlow 0.8s linear infinite', margin: '0 auto 14px' }} />
          <p style={{ fontWeight: 700, color: 'var(--white)', marginBottom: 4 }}>Generating interview questions...</p>
          <p style={{ fontSize: 12, color: 'var(--muted)' }}>Tailored to your profile and {scholarshipName}</p>
        </div>
      )}

      {/* Results */}
      {data && !loading && (
        <>
          {/* Overview */}
          <div className="afu" style={{ borderRadius: 16, padding: '20px', background: 'var(--bg-2)', border: '1px solid var(--y-border)', marginBottom: 16 }}>
            <p style={{ fontSize: 13, color: 'var(--muted)', lineHeight: 1.7, marginBottom: 12 }}>{data.overview}</p>
            <div style={{ display: 'flex', gap: 20, flexWrap: 'wrap' }}>
              {data.dresscode && <p style={{ fontSize: 12, color: 'var(--muted)' }}>👔 {data.dresscode}</p>}
              {data.preparationTimeline && <p style={{ fontSize: 12, color: 'var(--muted)' }}>📅 {data.preparationTimeline}</p>}
            </div>
          </div>

          {/* Do's and Don'ts */}
          <div className="afu" style={{ display: 'grid', gridTemplateColumns: '1fr 1fr', gap: 14, marginBottom: 16 }}>
            <div style={{ borderRadius: 14, padding: '18px', background: 'var(--bg-2)', border: '1px solid rgba(52,211,153,0.2)' }}>
              <h3 style={{ fontSize: 13, fontWeight: 700, color: '#34d399', marginBottom: 10, display: 'flex', alignItems: 'center', gap: 6 }}>
                <CheckCircle size={14} /> Do's
              </h3>
              {data.dosList?.map((d, i) => (
                <p key={i} style={{ fontSize: 12, color: 'var(--muted)', marginBottom: 5, paddingLeft: 12, borderLeft: '2px solid rgba(52,211,153,0.3)' }}>
                  {d}
                </p>
              ))}
            </div>
            <div style={{ borderRadius: 14, padding: '18px', background: 'var(--bg-2)', border: '1px solid rgba(248,113,113,0.2)' }}>
              <h3 style={{ fontSize: 13, fontWeight: 700, color: '#f87171', marginBottom: 10, display: 'flex', alignItems: 'center', gap: 6 }}>
                <XCircle size={14} /> Don'ts
              </h3>
              {data.dontsList?.map((d, i) => (
                <p key={i} style={{ fontSize: 12, color: 'var(--muted)', marginBottom: 5, paddingLeft: 12, borderLeft: '2px solid rgba(248,113,113,0.3)' }}>
                  {d}
                </p>
              ))}
            </div>
          </div>

          {/* Questions header */}
          <div className="afu" style={{ display: 'flex', alignItems: 'center', justifyContent: 'space-between', marginBottom: 12 }}>
            <h2 style={{ fontFamily: 'Space Grotesk', fontSize: 16, fontWeight: 700, color: 'var(--white)' }}>
              🎤 {data.commonQuestions?.length || 0} Practice Questions
            </h2>
            <button onClick={handleDownloadPDF}
              style={{ display: 'flex', alignItems: 'center', gap: 6, padding: '7px 14px', borderRadius: 9, background: 'var(--b-dim)', border: '1px solid var(--b-border)', color: 'var(--b-1)', fontSize: 12, cursor: 'pointer' }}>
              <Download size={12} /> Download PDF
            </button>
          </div>

          {/* Questions */}
          <div style={{ display: 'flex', flexDirection: 'column', gap: 10 }}>
            {data.commonQuestions?.map((q, idx) => {
              const c     = CAT_COLORS[q.category] || CAT_COLORS.default;
              const isExp  = expanded === idx;
              const isPrac = practicing === idx;
              const fb     = feedback[idx];

              return (
                <div key={idx} className="ch" style={{ borderRadius: 14, background: 'var(--bg-2)', border: `1px solid ${isExp ? 'var(--y-border)' : 'var(--border)'}`, overflow: 'hidden' }}>
                  <button style={{ width: '100%', display: 'flex', alignItems: 'center', gap: 12, padding: '16px 18px', background: 'none', border: 'none', cursor: 'pointer', textAlign: 'left' }}
                    onClick={() => setExpanded(isExp ? null : idx)}>
                    <span style={{ fontFamily: 'Space Grotesk', fontSize: 14, fontWeight: 800, color: c, minWidth: 28 }}>
                      {String(idx + 1).padStart(2, '0')}
                    </span>
                    <span style={{ fontSize: 10, fontWeight: 700, padding: '3px 10px', borderRadius: 99, background: `${c}15`, color: c, border: `1px solid ${c}30`, flexShrink: 0, textTransform: 'capitalize' }}>
                      {q.category}
                    </span>
                    <p style={{ flex: 1, fontSize: 13, fontWeight: 600, color: 'var(--white-1)' }}>{q.question}</p>
                    {isExp
                      ? <ChevronUp size={14} style={{ color: 'var(--muted)', flexShrink: 0 }} />
                      : <ChevronDown size={14} style={{ color: 'var(--muted)', flexShrink: 0 }} />}
                  </button>

                  {isExp && (
                    <div className="afi" style={{ padding: '0 18px 18px', borderTop: '1px solid var(--border)' }}>
                      {/* Tips */}
                      <div style={{ marginTop: 14, padding: '12px 14px', borderRadius: 10, background: 'rgba(52,211,153,0.05)', border: '1px solid rgba(52,211,153,0.15)', marginBottom: 12 }}>
                        <p style={{ fontSize: 11, fontWeight: 700, color: '#34d399', marginBottom: 4 }}>💡 How to Answer</p>
                        <p style={{ fontSize: 12, color: 'var(--muted)', lineHeight: 1.6 }}>{q.tips}</p>
                      </div>

                      {/* Sample answer */}
                      {q.sampleAnswer && (
                        <div style={{ padding: '12px 14px', borderRadius: 10, background: 'var(--b-dim)', border: '1px solid var(--b-border)', marginBottom: 12 }}>
                          <p style={{ fontSize: 11, fontWeight: 700, color: 'var(--b-1)', marginBottom: 4 }}>📝 Sample Structure</p>
                          <p style={{ fontSize: 12, color: 'var(--muted)', lineHeight: 1.6 }}>{q.sampleAnswer}</p>
                        </div>
                      )}

                      {/* Practice */}
                      <button onClick={() => { setPracticing(isPrac ? null : idx); setAnswer(''); }}
                        style={{ padding: '8px 16px', borderRadius: 9, fontSize: 12, fontWeight: 700, cursor: 'pointer', marginBottom: isPrac ? 10 : 0, background: isPrac ? 'var(--y-dim)' : 'var(--bg-3)', border: `1px solid ${isPrac ? 'var(--y-border)' : 'var(--border)'}`, color: isPrac ? 'var(--y)' : 'var(--muted)', transition: 'all 0.2s' }}>
                        {isPrac ? '✏️ Practicing...' : '🎯 Practice Answer'}
                      </button>

                      {isPrac && (
                        <div>
                          <textarea value={answer} onChange={(e) => setAnswer(e.target.value)} rows={5}
                            placeholder="Write your answer using the STAR method: Situation, Task, Action, Result..."
                            style={{ width: '100%', padding: '12px 14px', borderRadius: 10, background: 'var(--bg-3)', border: '1px solid var(--border)', color: 'var(--white-1)', fontSize: 12, outline: 'none', resize: 'none', lineHeight: 1.6, fontFamily: 'inherit', marginBottom: 8 }}
                            onFocus={(e) => e.target.style.borderColor = 'var(--y)'}
                            onBlur={(e)  => e.target.style.borderColor = 'var(--border)'} />
                          <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'center' }}>
                            <span style={{ fontSize: 11, color: 'var(--muted)' }}>{answer.split(/\s+/).filter(Boolean).length} words</span>
                            <button onClick={() => handleGetFeedback(q.question, idx)} disabled={feedbackLoading}
                              className="btn-p"
                              style={{ display: 'flex', alignItems: 'center', gap: 6, padding: '8px 18px', borderRadius: 9, background: feedbackLoading ? 'var(--bg-4)' : 'var(--g-y)', color: feedbackLoading ? 'var(--muted)' : '#000', fontSize: 12, fontWeight: 700, border: 'none', cursor: feedbackLoading ? 'not-allowed' : 'pointer' }}>
                              <Send size={12} /> {feedbackLoading ? 'Getting feedback...' : 'Get AI Feedback'}
                            </button>
                          </div>
                        </div>
                      )}

                      {/* Feedback */}
                      {fb && (
                        <div className="afi" style={{ marginTop: 12, borderRadius: 12, padding: '16px', background: 'var(--bg-3)', border: '1px solid var(--y-border)' }}>
                          <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'center', marginBottom: 12 }}>
                            <p style={{ fontSize: 13, fontWeight: 700, color: 'var(--white)' }}>✨ AI Feedback</p>
                            <div style={{ fontFamily: 'Space Grotesk', fontSize: 22, fontWeight: 900, color: scoreColor(fb.score) }}>
                              {fb.score}/10
                            </div>
                          </div>
                          <div style={{ height: 4, borderRadius: 99, background: 'var(--bg-4)', overflow: 'hidden', marginBottom: 12 }}>
                            <div style={{ height: '100%', width: `${fb.score * 10}%`, background: scoreColor(fb.score), borderRadius: 99 }} />
                          </div>
                          {fb.strengths?.length > 0 && (
                            <div style={{ marginBottom: 8 }}>
                              <p style={{ fontSize: 11, fontWeight: 700, color: '#34d399', marginBottom: 4 }}>✓ Strengths</p>
                              {fb.strengths.map((s, i) => <p key={i} style={{ fontSize: 12, color: 'var(--muted)', marginBottom: 2 }}>• {s}</p>)}
                            </div>
                          )}
                          {fb.improvements?.length > 0 && (
                            <div style={{ marginBottom: 8 }}>
                              <p style={{ fontSize: 11, fontWeight: 700, color: 'var(--y)', marginBottom: 4 }}>↑ Improvements</p>
                              {fb.improvements.map((s, i) => <p key={i} style={{ fontSize: 12, color: 'var(--muted)', marginBottom: 2 }}>• {s}</p>)}
                            </div>
                          )}
                          {fb.improvedAnswer && (
                            <div style={{ padding: '10px 12px', borderRadius: 9, background: 'var(--bg-4)', border: '1px solid var(--b-border)' }}>
                              <p style={{ fontSize: 11, fontWeight: 700, color: 'var(--b-1)', marginBottom: 4 }}>✨ Improved Answer</p>
                              <p style={{ fontSize: 12, color: 'var(--muted)', lineHeight: 1.6 }}>{fb.improvedAnswer}</p>
                            </div>
                          )}
                        </div>
                      )}
                    </div>
                  )}
                </div>
              );
            })}
          </div>

          {/* Bottom CTA */}
          <div className="afu" style={{ borderRadius: 16, padding: '24px', background: 'var(--bg-2)', border: '1px solid var(--y-border)', textAlign: 'center', marginTop: 20 }}>
            <p style={{ fontFamily: 'Space Grotesk', fontSize: 15, fontWeight: 700, color: 'var(--white)', marginBottom: 6 }}>📄 Download Complete Interview Guide</p>
            <p style={{ fontSize: 12, color: 'var(--muted)', marginBottom: 16 }}>
              {data.commonQuestions?.length} questions with tips, sample answers and practice spaces
            </p>
            <button onClick={handleDownloadPDF}
              className="btn-p"
              style={{ display: 'inline-flex', alignItems: 'center', gap: 8, padding: '12px 28px', borderRadius: 12, background: 'var(--g-y)', color: '#000', fontSize: 14, fontWeight: 700, border: 'none', cursor: 'pointer' }}>
              <Download size={16} /> Download PDF Guide
            </button>
          </div>
        </>
      )}

      {/* Empty */}
      {!data && !loading && (
        <div style={{ textAlign: 'center', padding: '64px 32px', borderRadius: 20, background: 'var(--bg-2)', border: '1px solid var(--border)' }}>
          <div style={{ display: 'flex', justifyContent: 'center', gap: 16, marginBottom: 24, alignItems: 'center' }}>
            {[70,100,70].map((s,i) => (
              <div key={i} style={{ width:s, height:s, borderRadius:'50%', background: i===1 ? 'radial-gradient(circle at 33% 33%, rgba(59,126,255,0.85), rgba(59,126,255,0.3) 50%, rgba(5,5,7,0.9))' : 'radial-gradient(circle at 33% 33%, rgba(245,197,24,0.85), rgba(245,197,24,0.3) 50%, rgba(5,5,7,0.9))', boxShadow:`inset -4px -4px 10px rgba(0,0,0,0.4), 0 0 ${s/3}px ${i===1?'rgba(59,126,255,0.15)':'rgba(245,197,24,0.12)'}`, animation:`float ${5+i}s ease-in-out infinite ${i*0.5}s` }} />
            ))}
          </div>
          <h2 style={{ fontFamily:'Space Grotesk', fontSize:22, fontWeight:800, color:'var(--white)', marginBottom:8 }}>Ready to practice?</h2>
          <p style={{ fontSize:13, color:'var(--muted)', maxWidth:400, margin:'0 auto 24px', lineHeight:1.7 }}>
            Enter a scholarship name to get 10 tailored interview questions with AI feedback and a downloadable PDF guide.
          </p>
          <div style={{ display:'grid', gridTemplateColumns:'repeat(3,1fr)', gap:10, maxWidth:400, margin:'0 auto' }}>
            {[
              { icon:'🎤', title:'10 Questions',  desc:'Profile-tailored'      },
              { icon:'✍️', title:'Practice Mode', desc:'Write + get AI score'  },
              { icon:'📄', title:'PDF Guide',     desc:'Download all questions' },
            ].map(({ icon, title, desc }) => (
              <div key={title} style={{ padding:'14px', borderRadius:12, background:'var(--bg-3)', border:'1px solid var(--border)', textAlign:'center' }}>
                <p style={{ fontSize:22, marginBottom:6 }}>{icon}</p>
                <p style={{ fontSize:12, fontWeight:700, color:'var(--white-2)', marginBottom:2 }}>{title}</p>
                <p style={{ fontSize:10, color:'var(--muted)' }}>{desc}</p>
              </div>
            ))}
          </div>
        </div>
      )}
    </div>
  );
}