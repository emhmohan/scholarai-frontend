import { useState, useEffect } from 'react';
import api from '../utils/api';
import toast from 'react-hot-toast';
import { Briefcase, Sparkles, Save, Download, Plus } from 'lucide-react';
import jsPDF from 'jspdf';

const SECTIONS = [
  { key: 'summary',      label: 'Professional Summary', placeholder: 'Brief overview of your background and goals...' },
  { key: 'experience',   label: 'Work / Research Experience', placeholder: 'Company/Lab — Role\n2022–2024\n• Achievement using STAR method\n• Quantified impact...' },
  { key: 'education',    label: 'Education',            placeholder: 'University Name\nDegree, Field — Year\nGPA: 8.5/10...' },
  { key: 'skills',       label: 'Technical Skills',     placeholder: 'Languages: Python, JavaScript, C++\nFrameworks: TensorFlow, React\nTools: Docker, Git...' },
  { key: 'projects',     label: 'Projects',             placeholder: 'Project Name — Link\nDescription and impact...' },
  { key: 'publications', label: 'Publications',         placeholder: 'Title, Conference/Journal, Year...' },
  { key: 'awards',       label: 'Awards & Honors',      placeholder: 'Award name — Organization — Year...' },
];

export default function ResumePage() {
  const [resumes,   setResumes]   = useState([]);
  const [current,   setCurrent]   = useState(null);
  const [sections,  setSections]  = useState({ summary: '', experience: '', education: '', skills: '', projects: '', publications: '', awards: '' });
  const [title,     setTitle]     = useState('My Resume');
  const [loading,   setLoading]   = useState(true);
  const [saving,    setSaving]    = useState(false);
  const [enhancing, setEnhancing] = useState(false);
  const [enhanced,  setEnhanced]  = useState(null);
  const [activeTab, setActiveTab] = useState('summary');

  useEffect(() => { fetchResumes(); }, []);

  const fetchResumes = async () => {
    setLoading(false);
    try {
      const res = await api.get('/resume');
      const list = res.data.data?.resumes || [];
      setResumes(list);
      if (list.length > 0) {
        const r = list[0];
        setCurrent(r._id);
        setSections(r.sections || {});
        setTitle(r.title || 'My Resume');
      }
    } catch { /* silent */ }
  };

  const handleSave = async () => {
    setSaving(true);
    try {
      const payload = { title, sections: JSON.stringify(sections) };
      if (current) {
        await api.put(`/resume/${current}`, payload);
        toast.success('Resume saved!');
      } else {
        const res = await api.post('/resume', payload);
        setCurrent(res.data.data?.resume?._id);
        toast.success('Resume created!');
      }
      fetchResumes();
    } catch { toast.error('Failed to save resume'); }
    finally  { setSaving(false); }
  };

  const handleEnhance = async () => {
    if (!current) { toast.error('Save resume first'); return; }
    setEnhancing(true);
    try {
      const res = await api.post(`/resume/${current}/enhance`);
      setEnhanced(res.data.data);
      toast.success('AI enhancement ready!');
    } catch { toast.error('Failed to enhance resume'); }
    finally  { setEnhancing(false); }
  };

  const handleDownloadPDF = () => {
    const doc        = new jsPDF();
    const pageWidth  = doc.internal.pageSize.getWidth();
    const pageHeight = doc.internal.pageSize.getHeight();
    const margin     = 20;

    doc.setFillColor(5, 5, 7);
    doc.rect(0, 0, pageWidth, 36, 'F');
    doc.setFillColor(245, 197, 24);
    doc.rect(0, 0, 4, 36, 'F');
    doc.setTextColor(255, 255, 255);
    doc.setFontSize(18);
    doc.setFont('helvetica', 'bold');
    doc.text(title, margin + 4, 16);
    doc.setFontSize(9);
    doc.setFont('helvetica', 'normal');
    doc.text(`Generated by ScholarAI · ${new Date().toLocaleDateString()}`, margin + 4, 27);

    let y = 46;
    SECTIONS.forEach(({ key, label }) => {
      const content = sections[key];
      if (!content?.trim()) return;
      if (y > pageHeight - 30) { doc.addPage(); y = 20; }
      doc.setFillColor(20, 20, 26);
      doc.rect(margin, y - 4, pageWidth - margin * 2, 10, 'F');
      doc.setFontSize(10);
      doc.setFont('helvetica', 'bold');
      doc.setTextColor(245, 197, 24);
      doc.text(label.toUpperCase(), margin + 4, y + 3);
      y += 12;
      doc.setTextColor(220, 220, 220);
      doc.setFontSize(10);
      doc.setFont('helvetica', 'normal');
      const lines = doc.splitTextToSize(content, pageWidth - margin * 2 - 4);
      lines.forEach((line) => {
        if (y + 6 > pageHeight - 20) { doc.addPage(); y = 20; }
        doc.text(line, margin + 4, y);
        y += 5.5;
      });
      y += 6;
    });

    doc.save(`Resume_${title.replace(/\s+/g,'_')}.pdf`);
    toast.success('PDF downloaded!');
  };

  return (
    <div style={{ maxWidth: 1100, margin: '0 auto' }}>

      {/* Header */}
      <div className="afu" style={{ display: 'flex', alignItems: 'flex-start', justifyContent: 'space-between', flexWrap: 'wrap', gap: 16, marginBottom: 24 }}>
        <div style={{ display: 'flex', alignItems: 'center', gap: 12 }}>
          <div style={{ width: 38, height: 38, borderRadius: 11, background: 'var(--y-dim)', border: '1px solid var(--y-border)', display: 'flex', alignItems: 'center', justifyContent: 'center' }}>
            <Briefcase size={19} style={{ color: 'var(--y)' }} />
          </div>
          <div>
            <h1 style={{ fontFamily: 'Space Grotesk', fontSize: 22, fontWeight: 800, color: 'var(--white)' }}>Resume Builder</h1>
            <p style={{ fontSize: 13, color: 'var(--muted)' }}>ATS-optimized with AI enhancement</p>
          </div>
        </div>
        <div style={{ display: 'flex', gap: 10, flexWrap: 'wrap' }}>
          <button onClick={handleDownloadPDF}
            style={{ display: 'flex', alignItems: 'center', gap: 6, padding: '9px 16px', borderRadius: 10, background: 'var(--bg-3)', border: '1px solid var(--border)', color: 'var(--muted)', fontSize: 13, cursor: 'pointer', transition: 'all 0.2s' }}
            onMouseEnter={(e) => { e.currentTarget.style.borderColor = 'var(--border-2)'; e.currentTarget.style.color = 'var(--white-2)'; }}
            onMouseLeave={(e) => { e.currentTarget.style.borderColor = 'var(--border)'; e.currentTarget.style.color = 'var(--muted)'; }}>
            <Download size={13} /> PDF
          </button>
          <button onClick={handleEnhance} disabled={enhancing}
            style={{ display: 'flex', alignItems: 'center', gap: 6, padding: '9px 16px', borderRadius: 10, background: 'var(--b-dim)', border: '1px solid var(--b-border)', color: 'var(--b-1)', fontSize: 13, fontWeight: 700, cursor: enhancing ? 'not-allowed' : 'pointer' }}>
            <Sparkles size={13} /> {enhancing ? 'Enhancing...' : 'AI Enhance'}
          </button>
          <button onClick={handleSave} disabled={saving}
            className="btn-p"
            style={{ display: 'flex', alignItems: 'center', gap: 6, padding: '9px 20px', borderRadius: 10, background: saving ? 'var(--bg-4)' : 'var(--g-y)', color: saving ? 'var(--muted)' : '#000', fontSize: 13, fontWeight: 700, border: 'none', cursor: saving ? 'not-allowed' : 'pointer' }}>
            <Save size={13} /> {saving ? 'Saving...' : 'Save Resume'}
          </button>
        </div>
      </div>

      {/* Title */}
      <div className="afu" style={{ marginBottom: 20 }}>
        <input value={title} onChange={(e) => setTitle(e.target.value)}
          placeholder="Resume title..."
          style={{ width: '100%', padding: '12px 16px', borderRadius: 12, background: 'var(--bg-2)', border: '1px solid var(--border)', color: 'var(--white)', fontSize: 16, fontWeight: 700, fontFamily: 'Space Grotesk', outline: 'none' }}
          onFocus={(e) => { e.target.style.borderColor = 'var(--y)'; e.target.style.boxShadow = '0 0 0 3px rgba(245,197,24,0.08)'; }}
          onBlur={(e)  => { e.target.style.borderColor = 'var(--border)'; e.target.style.boxShadow = 'none'; }} />
      </div>

      <div style={{ display: 'grid', gridTemplateColumns: '200px 1fr', gap: 16, alignItems: 'start' }}>

        {/* Section tabs */}
        <div style={{ borderRadius: 14, background: 'var(--bg-2)', border: '1px solid var(--border)', overflow: 'hidden', position: 'sticky', top: 'calc(var(--nav-h) + 16px)' }}>
          {SECTIONS.map(({ key, label }) => {
            const filled  = !!(sections[key]?.trim());
            const isActive = activeTab === key;
            return (
              <button key={key} onClick={() => setActiveTab(key)}
                style={{ display: 'flex', alignItems: 'center', gap: 10, width: '100%', padding: '12px 16px', border: 'none', borderLeft: `3px solid ${isActive ? 'var(--y)' : 'transparent'}`, background: isActive ? 'var(--y-dim)' : 'transparent', cursor: 'pointer', textAlign: 'left', transition: 'all 0.2s' }}>
                <div style={{ width: 6, height: 6, borderRadius: '50%', background: filled ? '#34d399' : 'var(--border)', flexShrink: 0 }} />
                <span style={{ fontSize: 12, fontWeight: isActive ? 700 : 500, color: isActive ? 'var(--y)' : 'var(--muted)', lineHeight: 1.3 }}>{label}</span>
              </button>
            );
          })}
        </div>

        {/* Editor */}
        <div style={{ display: 'flex', flexDirection: 'column', gap: 16 }}>
          {SECTIONS.filter((s) => s.key === activeTab).map(({ key, label, placeholder }) => (
            <div key={key} style={{ borderRadius: 16, background: 'var(--bg-2)', border: '1px solid var(--border)', overflow: 'hidden' }}>
              <div style={{ padding: '14px 20px', borderBottom: '1px solid var(--border)', background: 'var(--bg-3)', display: 'flex', justifyContent: 'space-between', alignItems: 'center' }}>
                <h3 style={{ fontFamily: 'Space Grotesk', fontSize: 14, fontWeight: 700, color: 'var(--white)' }}>{label}</h3>
                <span style={{ fontSize: 11, color: 'var(--muted)' }}>{sections[key]?.split(/\s+/).filter(Boolean).length || 0} words</span>
              </div>
              <textarea
                value={sections[key] || ''}
                onChange={(e) => setSections((p) => ({ ...p, [key]: e.target.value }))}
                placeholder={placeholder}
                rows={10}
                style={{ width: '100%', padding: '16px 20px', background: 'transparent', border: 'none', color: 'var(--white-1)', fontSize: 13, lineHeight: 1.7, outline: 'none', resize: 'vertical', fontFamily: 'inherit' }} />
            </div>
          ))}

          {/* AI Enhancement panel */}
          {enhanced && (
            <div className="afi" style={{ borderRadius: 16, background: 'var(--bg-2)', border: '1px solid var(--b-border)', overflow: 'hidden' }}>
              <div style={{ padding: '14px 20px', borderBottom: '1px solid var(--border)', background: 'var(--bg-3)', display: 'flex', alignItems: 'center', gap: 8 }}>
                <Sparkles size={15} style={{ color: 'var(--b-1)' }} />
                <h3 style={{ fontFamily: 'Space Grotesk', fontSize: 14, fontWeight: 700, color: 'var(--white)' }}>AI Enhancement Results</h3>
              </div>
              <div style={{ padding: '20px' }}>
                {enhanced.summary && (
                  <div style={{ marginBottom: 16 }}>
                    <p style={{ fontSize: 11, fontWeight: 700, color: 'var(--y)', marginBottom: 8, textTransform: 'uppercase', letterSpacing: '0.06em' }}>Enhanced Summary</p>
                    <p style={{ fontSize: 13, color: 'var(--muted)', lineHeight: 1.7 }}>{enhanced.summary}</p>
                  </div>
                )}
                {enhanced.keywords?.length > 0 && (
                  <div style={{ marginBottom: 16 }}>
                    <p style={{ fontSize: 11, fontWeight: 700, color: 'var(--b-1)', marginBottom: 8, textTransform: 'uppercase', letterSpacing: '0.06em' }}>ATS Keywords</p>
                    <div style={{ display: 'flex', flexWrap: 'wrap', gap: 6 }}>
                      {enhanced.keywords.map((k) => (
                        <span key={k} style={{ fontSize: 12, padding: '4px 12px', borderRadius: 99, background: 'var(--b-dim)', border: '1px solid var(--b-border)', color: 'var(--b-1)' }}>{k}</span>
                      ))}
                    </div>
                  </div>
                )}
                {enhanced.missing?.length > 0 && (
                  <div>
                    <p style={{ fontSize: 11, fontWeight: 700, color: '#f87171', marginBottom: 8, textTransform: 'uppercase', letterSpacing: '0.06em' }}>Missing Sections</p>
                    {enhanced.missing.map((m) => (
                      <p key={m} style={{ fontSize: 12, color: 'var(--muted)', marginBottom: 4 }}>• {m}</p>
                    ))}
                  </div>
                )}
              </div>
            </div>
          )}
        </div>
      </div>
    </div>
  );
}